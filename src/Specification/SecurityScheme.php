<?php

namespace Mathrix\OpenAPI\Specification;

/**
 * Class SecurityScheme.
 *
 * @link https://github.com/OAI/OpenAPI-Specification/blob/master/versions/3.0.2.md#security-scheme-object
 *
 * @author Mathieu Bour <mathieu@mathrix.fr>
 * @copyright Mathrix Education SA.
 * @since 0.9.0
 */
class SecurityScheme extends BaseObject
{
    /**
     * @var string $type REQUIRED. The type of the security scheme. Valid values are "apiKey", "http", "oauth2",
     *     "openIdConnect".
     */
    public $type;
    /**
     * @var string $description A short description for security scheme. CommonMark syntax MAY be used for rich text
     *     representation.
     */
    public $description;
    /** @var string $name REQUIRED. The name of the header, query or cookie parameter to be used. */
    public $name;
    /** @var string $in REQUIRED. The location of the API key. Valid values are "query", "header" or "cookie". */
    public $in;
    /**
     * @var string $scheme REQUIRED. The name of the HTTP Authorization scheme to be used in the Authorization header
     *     as defined in RFC7235.
     * @link https://tools.ietf.org/html/rfc7235#section-5.1 RFC7235
     */
    public $scheme;
    /**
     * @var string $bearerFormat A hint to the client to identify how the bearer token is formatted. Bearer tokens are
     *     usually generated by an authorization server, so this information is primarily for documentation purposes.
     */
    public $bearerFormat;
    // public $flows;
    /**
     * @var string REQUIRED. OpenId Connect URL to discover OAuth2 configuration values. This MUST be in the form of a
     *     URL.
     */
    public $openIdConnectUrl;
}
